"""Check every appendix run against the experimental setting stated in the FedASMU paper.

The paper values below are transcribed again, independently of
configs/common/paper_settings.yaml, from arXiv 2312.05770v1:
  - Appendix "Experiment details": 100 devices; slowest device 5x slower than the
    fastest, times sampled independently in that range; learning-rate decay; 500 epochs
    for synchronous, 5000 for asynchronous approaches; parallelism 10 % of the devices.
  - Tables 5 and 6: m, m', tau, T, eta_lambda, eta_sigma, eta_iota, eta_gamma,
    eta_upsilon, eta_i, eta_RL for each model/dataset.
For each run the check uses both the configuration recorded in its manifest and what the
logs show actually happened (concurrency, staleness, number of updates or rounds, device
speed spread, identical data split and initial weights across the three methods).

Output: results/reports/paper_settings_check.md
"""
import json
import os

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MET = os.path.join(ROOT, "results", "metrics")
OUT = os.path.join(ROOT, "results", "reports", "paper_settings_check.md")

# (eta_lambda, eta_sigma, eta_iota, eta_gamma, eta_upsilon, eta_i, eta_RL)  Tables 5-6
TABLE = {
    "lenet5-fmnist": (1e-4, 1e-4, 1e-4, 1e-4, 1e-4, 0.005, 1e-3),
    "lenet5-cifar10": (1e-3, 1e-3, 0.1, 0.1, 1e-3, 0.03, 1e-3),
    "lenet5-cifar100": (1e-4, 1e-4, 1e-4, 1e-4, 1e-4, 0.03, 1e-3),
    "cnn-cifar10": (1e-3, 1e-3, 1e-4, 0.1, 1e-3, 0.028, 1e-3),
    "cnn-cifar100": (1e-5, 1e-5, 1e-5, 1e-5, 1e-5, 0.013, 1e-3),
    "resnet20-cifar100": (1e-4, 1e-4, 1e-4, 1e-4, 1e-4, 0.03, 1e-3),
    "resnet20-tinyimagenet": (1e-4, 1e-4, 1e-4, 1e-4, 1e-4, 0.03, 1e-3),
    "alexnet-cifar10": (1e-4, 1e-4, 1e-4, 1e-4, 1e-4, 0.03, 1e-3),
    "alexnet-cifar100": (1e-4, 1e-4, 1e-4, 1e-4, 1e-4, 0.03, 1e-3),
    "vgg11-cifar10": (1e-4, 1e-4, 1e-4, 1e-4, 1e-4, 0.03, 1e-3),
    "vgg11-cifar100": (1e-4, 1e-4, 1e-4, 1e-4, 1e-4, 0.03, 1e-3),
    "textcnn-imdb": (1e-4, 1e-4, 1e-4, 1e-4, 1e-4, 0.001, 1e-3),
}
COMMON = {"num_devices": 100, "max_concurrency": 10, "staleness_bound": 99, "trigger_period": 10, "hetero": 5.0}
KEYS = ("eta_lambda", "eta_sigma", "eta_iota", "eta_gamma", "eta_upsilon")


def check_run(d, algo):
    m = json.load(open(os.path.join(d, "manifest.json")))
    c = m["config"]
    wl = f"{c['model']}-{c['dataset']}"
    out = []

    def add(name, ok, detail):
        out.append((name, "PASS" if ok else "FAIL", detail))

    for k, v in COMMON.items():
        add(k, c[k] == v, f"{c[k]} (paper {v})")
    p = TABLE[wl]
    add("eta_i (local lr)", abs(c["local"]["lr"] - p[5]) < 1e-12, f"{c['local']['lr']} (paper {p[5]})")
    if algo == "fedasmu":
        for k, v in zip(KEYS, p[:5]):
            add(k, abs(c["fedasmu"][k] - v) < 1e-12, f"{c['fedasmu'][k]} (paper {v})")
        add("eta_RL", abs(c["fedasmu"]["eta_rl"] - p[6]) < 1e-12, f"{c['fedasmu']['eta_rl']} (paper {p[6]})")
    ev = pd.read_csv(os.path.join(d, "eval.csv"))
    st = json.load(open(os.path.join(d, "status.json"))).get("status")
    add("run completed", st == "COMPLETED", st)
    if algo == "fedavg":
        add("budget: 500 rounds", int(ev.global_version.max()) == 500, f"{int(ev.global_version.max())} rounds")
    else:
        add("budget: 5000 updates", int(ev.received.max()) == 5000, f"{int(ev.received.max())} received")
        add("concurrency <= 10 (logged)", int(ev.running.max()) <= 10, f"max {int(ev.running.max())}")
        up = pd.read_csv(os.path.join(d, "updates.csv"))
        add("staleness bound 99 respected", int(up[up.accepted == True].staleness.max()) <= 99,  # noqa: E712
            f"max accepted staleness {int(up[up.accepted == True].staleness.max())}")  # noqa: E712
    ps = m.get("profiles_summary", {})
    if ps:
        r = ps["epoch_time_max"] / ps["epoch_time_min"]
        add("device speed spread <= 5x", r <= 5.0, f"slowest/fastest = {r:.2f}")
    add("non-IID Dirichlet split", m["partition_meta"]["alpha"] == c["dirichlet_alpha"],
        f"alpha {c['dirichlet_alpha']} (assumption; paper gives none)")
    return wl, out, m


def main():
    lines = ["# Appendix runs vs the paper's stated experimental setting", "",
             "Generated by `scripts/check_paper_settings.py`. Paper values transcribed from arXiv 2312.05770v1 "
             "(appendix 'Experiment details', Tables 5-6), independently of the config files.", ""]
    summary = []
    fair = {}
    for name in sorted(os.listdir(MET)):
        if not name.startswith("appendix_") or not os.path.exists(os.path.join(MET, name, "manifest.json")):
            continue
        algo = name.split("_")[-2]
        try:
            wl, res, m = check_run(os.path.join(MET, name), algo)
        except Exception as e:  # incomplete run
            summary.append((name, "-", f"not checked ({type(e).__name__})"))
            continue
        fair.setdefault(wl, []).append((algo, m["partition_meta"]["sha256"],
                                        m["config"]["init_weights"], json.dumps(m.get("profiles_summary"))))
        nfail = sum(r[1] == "FAIL" for r in res)
        summary.append((name, f"{len(res) - nfail}/{len(res)}", "; ".join(f"{a}: {c}" for a, s, c in res if s == "FAIL")))
        lines += [f"## {name}", "", "| check | result | value |", "|---|---|---|"]
        lines += [f"| {a} | {s} | {c} |" for a, s, c in res] + [""]
    lines[5:5] = ["## Summary", "", "| run | passed | failures |", "|---|---|---|"] + \
                 [f"| {a} | {b} | {c} |" for a, b, c in summary] + [""]
    fl = ["## Same data split, initial weights and device profiles across methods", "",
          "| workload | methods | same split | same init | same device profiles |", "|---|---|---|---|---|"]
    for wl, v in sorted(fair.items()):
        fl.append(f"| {wl} | {', '.join(a for a, *_ in v)} | {len({x[1] for x in v}) == 1} | "
                  f"{len({x[2] for x in v}) == 1} | {len({x[3] for x in v}) == 1} |")
    lines[5:5] = fl + [""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(lines) + "\n")
    for a, b, c in summary:
        print(f"{a:45s} {b:6s} {c}")
    print("\n".join(fl))


if __name__ == "__main__":
    main()
